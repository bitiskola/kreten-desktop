export function resolveLanguage(preference: string | undefined, locales: readonly string[] = []): Language {
  if (preference === 'hu' || preference === 'en' || preference === 'de') return preference;
  for (const locale of locales) {
    const language = locale.toLowerCase().split(/[-_]/)[0];
    if (language === 'hu' || language === 'en' || language === 'de') return language;
  }
  return 'hu';
}

/** Only known static UI copy is translated; unknown text passes through intact. */
export function translate(language: Language, text: string, values: Record<string, string | number> = {}): string {
  const translated = language === 'hu' ? text : translations[text]?.[language] ?? text;
  return translated.replace(/\{(\w+)\}/g, (placeholder, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : placeholder);
}

export const createTranslator = (language: Language) =>
  (text: string, values?: Record<string, string | number>) => translate(language, text, values);

export const dateLocale = (language: Language) => ({ hu: 'hu-HU', en: 'en-GB', de: 'de-DE' })[language];

let currentLanguage: Language = 'hu';
export const currentDateLocale = () => dateLocale(currentLanguage);
export const currentLanguageCode = (): Language => currentLanguage;
/** Call during application language setup; React state owns rerendering. */
export function setLanguage(language: Language): void { currentLanguage = language; }
export function t(text: string, language: Language = currentLanguage, values?: Record<string, string | number>): string {
  return translate(language, text, values);
}

